// Generates css/palette.css from the GIMP palette ../palettes/nord.gpl:
// one custom property per named colour (--nord-<name>), plus a "-deep"
// variant of each accent (Frost, Aurora) for the light theme: the accent
// with its OKLCH lightness lowered (hue and chroma kept) just enough to
// reach 4.5:1 on the light panel (Snow Storm 3). Every colour of the app
// comes from these.
//
// Usage: bun scripts/palette.js            write css/palette.css and print
//                                          the token contrast table
//        bun scripts/palette.js --check    exit 1 if css/palette.css is stale

import { join } from "node:path"

const root = join(import.meta.dir, "..")
export const GPL = join(root, "../palettes/nord.gpl")
export const OUT = join(root, "css/palette.css")
export const TOKENS = join(root, "css/tokens.css")

/** The neutral colours; the others are accents and get a "-deep" variant. */
const NEUTRAL = /polar night|snow storm/i
/** Accents are darkened until they reach MIN_CONTRAST on this colour (the light theme's panel). */
const LIGHT_REFERENCE = "Snow Storm 3"
export const MIN_CONTRAST = 4.5

export const slug = name => name.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")

/** [{name, slug, rgb: [r, g, b], hex}] from a GIMP .gpl palette. */
export function parseGpl(text) {
  const out = []
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*(\d{1,3})\s+(\d{1,3})\s+(\d{1,3})\s+(.+?)\s*$/.exec(line)
    if (!m) continue
    const rgb = [m[1], m[2], m[3]].map(Number)
    out.push({ name: m[4], slug: slug(m[4]), rgb, hex: hex(rgb) })
  }
  return out
}

export const hex = rgb => "#" + rgb.map(v => v.toString(16).padStart(2, "0")).join("")
export const fromHex = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16))

/** WCAG 2 relative luminance and contrast ratio. */
export function luminance([r, g, b]) {
  const f = v => (v /= 255) <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
}
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}

/** sRGB (0-255) <-> OKLab (Björn Ottosson's matrices). */
const lin = v => (v /= 255) <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
const unlin = v => 255 * (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055)
export function toOklab(rgb) {
  const [r, g, b] = rgb.map(lin)
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s]
}
export function fromOklab([L, a, b]) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s]
    .map(v => Math.max(0, Math.min(255, Math.round(unlin(Math.max(0, v))))))
}

/** The palette plus the "-deep" accents, as [{slug, hex, comment}]. */
export function properties(colours) {
  const by = Object.fromEntries(colours.map(c => [c.name, c]))
  const ref = by[LIGHT_REFERENCE]?.rgb
  if (!ref) throw new Error(`the palette needs "${LIGHT_REFERENCE}"`)
  const props = colours.map(c => ({ slug: c.slug, hex: c.hex, comment: c.name }))
  for (const c of colours) {
    if (NEUTRAL.test(c.name)) continue
    const [L0, a, b] = toOklab(c.rgb)
    let L = L0, rgb = c.rgb
    while (contrast(rgb, ref) < MIN_CONTRAST && L > 0) rgb = fromOklab([L -= 0.005, a, b])
    const cr = contrast(rgb, ref).toFixed(2)
    props.push({
      slug: `${c.slug}-deep`, hex: hex(rgb),
      comment: L < L0 ? `${c.name}, OKLCH lightness ${L0.toFixed(3)} -> ${L.toFixed(3)}: ${cr}:1 on ${LIGHT_REFERENCE}`
                      : `${c.name} (already ${cr}:1 on ${LIGHT_REFERENCE})`,
    })
  }
  return props
}

export function paletteCss(gplText) {
  const colours = parseGpl(gplText)
  const name = /^Name:\s*(.+)$/m.exec(gplText)?.[1]?.trim() ?? "palette"
  const lines = properties(colours).map(p => `  --nord-${p.slug}: ${p.hex}; /* ${p.comment} */`)
  return `/* Generated by scripts/palette.js from palettes/nord.gpl ("${name}").
   Do not edit: change the .gpl file and run \`bun scripts/palette.js\`.
   The -deep accents are for text on the light theme. */

:root {
${lines.join("\n")}
}
`
}

/**
 * The --tok-*, --diag-* and other colour properties of tokens.css, resolved
 * to hex for both themes: {light: {name: hex}, dark: {name: hex}}. Values
 * are var(--nord-…) or light-dark(var(--nord-…), var(--nord-…)).
 */
export function themeColours(tokensCss, paletteCssText) {
  const nord = {}
  for (const m of paletteCssText.matchAll(/--(nord-[a-z0-9-]+):\s*(#[0-9a-f]{6})/g)) nord[m[1]] = m[2]
  const v = s => {
    const m = /^var\(--(nord-[a-z0-9-]+)\)$/.exec(s.trim())
    return m ? nord[m[1]] : undefined
  }
  const light = {}, dark = {}
  const block = [...tokensCss.matchAll(/:root\s*\{([^}]*)\}/g)].map(m => m[1]).join("\n")
  for (const m of block.matchAll(/--([a-z_-]+):\s*([^;]+);/g)) {
    const val = m[2].trim()
    const ld = /^light-dark\((.+),\s*(var\([^)]*\))\)$/.exec(val)
    if (ld) { light[m[1]] = v(ld[1]); dark[m[1]] = v(ld[2]) }
    else if (v(val)) light[m[1]] = dark[m[1]] = v(val)
  }
  return { light, dark }
}

/** Contrast of every text colour (--fg, --muted, --tok-*) on the editor backgrounds. */
export function contrastTable(themes) {
  const rows = []
  for (const [theme, c] of Object.entries(themes)) {
    for (const [name, value] of Object.entries(c)) {
      if (!value || !(name === "fg" || name === "muted" || name.startsWith("tok-"))) continue
      rows.push({
        theme, name, hex: value,
        bg: contrast(fromHex(value), fromHex(c.bg)),
        line: contrast(fromHex(value), fromHex(c["cursor-line"])),
      })
    }
  }
  return rows
}

if (import.meta.main) {
  const css = paletteCss(await Bun.file(GPL).text())
  if (process.argv.includes("--check")) {
    const ok = (await Bun.file(OUT).exists()) && (await Bun.file(OUT).text()) === css
    if (!ok) { console.error("css/palette.css is stale: run bun scripts/palette.js"); process.exit(1) }
    process.exit(0)
  }
  await Bun.write(OUT, css)
  console.log(`wrote css/palette.css`)
  const rows = contrastTable(themeColours(await Bun.file(TOKENS).text(), css))
  console.log("\ncontrast on the editor background / on the active line (WCAG, 4.5 for normal text):")
  for (const r of rows) {
    const flag = r.bg < MIN_CONTRAST ? "  < 4.5" : ""
    console.log(`${r.theme.padEnd(6)} ${r.name.padEnd(20)} ${r.hex}  ${r.bg.toFixed(2).padStart(5)}  ${r.line.toFixed(2).padStart(5)}${flag}`)
  }
}
